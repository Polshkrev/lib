/**
 * @brief General-purpose C++ utilities.
 *
 * The `polutils` namespace provides utilities and abstractions intended to simplify common programming tasks.
 *
 * The namespace is organized into specialized sub-namespaces and components covering collections, file system operations, and other general-purpose functionality.
 *
 * Namespaces:
 *
 * The namespaces provided are:
 *
 * - `collections` — Generic collection types and utilities.
 *
 * - `fayl` — File system utilities.
 *
 * Collections:
 *
 * The `collections` namespace provides generic data structures for storing and manipulating collections of values.
 *
 * The collection utilities include:
 *
 * - Array-based collections.
 *
 * - Dynamically resizable arrays.
 *
 * - Common collection interfaces and functionality.
 *
 * Fayl:
 *
 * The `fayl` namespace provides low-level utilities for interacting with the file system.
 *
 * The file system utilities include:
 *
 * - Paths and path manipulation.
 *
 * - File system entries.
 *
 * - Directory management.
 *
 * - File collections.
 */
